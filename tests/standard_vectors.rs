// Public-standard known-answer tests guard the pinned dependency and feature selection against
// primitive-level drift. They do not claim cross-implementation coverage for complete envelopes.

#[test]
fn sm2_verification_matches_gbt_32918_2_2017_appendix_a_2() {
    // This KAT pins public-key verification only. Complete-envelope compatibility remains covered
    // by neutral round trips and the external private compatibility suite.
    let public_sec1 = [
        0x04, 0x09, 0xf9, 0xdf, 0x31, 0x1e, 0x54, 0x21, 0xa1, 0x50, 0xdd, 0x7d, 0x16, 0x1e, 0x4b,
        0xc5, 0xc6, 0x72, 0x17, 0x9f, 0xad, 0x18, 0x33, 0xfc, 0x07, 0x6b, 0xb0, 0x8f, 0xf3, 0x56,
        0xf3, 0x50, 0x20, 0xcc, 0xea, 0x49, 0x0c, 0xe2, 0x67, 0x75, 0xa5, 0x2d, 0xc6, 0xea, 0x71,
        0x8c, 0xc1, 0xaa, 0x60, 0x0a, 0xed, 0x05, 0xfb, 0xf3, 0x5e, 0x08, 0x4a, 0x66, 0x32, 0xf6,
        0x07, 0x2d, 0xa9, 0xad, 0x13,
    ];
    // Exact public-standard identity bytes from the appendix.
    let standard_identity = [
        0x41, 0x4c, 0x49, 0x43, 0x45, 0x31, 0x32, 0x33, 0x40, 0x59, 0x41, 0x48, 0x4f, 0x4f, 0x2e,
        0x43, 0x4f, 0x4d,
    ];
    // Canonical DER: r needs a leading zero because its high bit is set; s does not.
    let signature_der = [
        0x30, 0x45, 0x02, 0x21, 0x00, 0x88, 0x34, 0x8a, 0x09, 0xa3, 0xe3, 0x24, 0xc4, 0xfe, 0x94,
        0x68, 0x43, 0x12, 0x3e, 0x40, 0xc1, 0x75, 0x46, 0x8f, 0x3e, 0x36, 0x48, 0x18, 0x85, 0x84,
        0x4a, 0x14, 0x4d, 0x21, 0x67, 0xea, 0x4c, 0x02, 0x20, 0x0a, 0xd2, 0xce, 0x55, 0x2f, 0xd3,
        0x3e, 0xab, 0x79, 0x2e, 0x5a, 0x28, 0x05, 0xe0, 0x50, 0x4d, 0x01, 0x4c, 0x96, 0x13, 0x5f,
        0x8e, 0x03, 0x89, 0x10, 0x87, 0x13, 0x2a, 0xbb, 0x24, 0xd4, 0x8d,
    ];
    let public = Sm2PublicKey::from_sec1_bytes(&public_sec1).expect("standard public point");

    assert!(sm2::verify_with_id(
        &public,
        &standard_identity,
        b"message digest",
        &signature_der,
    ));
    assert!(!sm2::verify_with_id(
        &public,
        &standard_identity,
        b"message digesu",
        &signature_der,
    ));
}

